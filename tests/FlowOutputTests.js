'use strict';
const assert = require('node:assert/strict');
require('../ui/flow-output.js');
const { create, iperfResult } = globalThis.TerminalGridFlowOutput;
const log = create();
const ansi = Buffer.from('C:\\test>echo NAN started\r\n\x1b[32mNAN 已啟動\x1b[0m\r\n');
for (const byte of ansi) log.feed(Uint8Array.of(byte));
assert.equal(log.match('NAN started', 'echo NAN started'), false);
assert.equal(log.match('NAN 已啟動', 'echo NAN started'), true);
assert.equal(log.text().includes('\x1b'), false);
const finished = '[  5] 0.00-10.00 sec  1.1 GBytes 941 Mbits/sec receiver\r\niperf Done.\r\n';
assert.equal(iperfResult(finished).rate, '941 Mbits/sec');
assert.match(iperfResult(finished).status, /receiver/);
assert.equal(iperfResult(finished + 'C:\\test>iperf3 -c 192.0.2.10\r\n[ 5] 0-1 sec  100 Mbits/sec').rate, '');
assert.equal(iperfResult(finished + 'PS C:\\test> & "C:\\iperf folder\\iperf3.exe" -c 192.0.2.10').rate, '');
assert.match(iperfResult(finished + 'iperf3: error - unable to connect').status, /有錯誤/);
assert.equal(iperfResult('^C\r\n' + finished).rate, '');
assert.equal(iperfResult('[SUM] 0-10 sec 800 Mbits/sec receiver\r\n[ 3] 0-10 sec 400 Mbits/sec receiver').rate, '800 Mbits/sec');
assert.equal(iperfResult('Server Report:\r\n[ 3] 0-10 sec 800 Mbits/sec').rate, '800 Mbits/sec');
assert.match(iperfResult('Server Report:\r\n').status, /未找到/);
assert.equal(iperfResult(finished).state, 'completed');
assert.deepEqual(iperfResult(finished).lines, finished.trim().split('\r\n'));
const interrupted = iperfResult(finished + 'C:\\test>iperf3 -c 192.0.2.20\r\nConnecting to host 192.0.2.20, port 5201\r\n^C\r\n' + finished);
assert.equal(interrupted.state, 'interrupted');
assert.equal(interrupted.rate, '');
assert.deepEqual(interrupted.lines, ['^C']);
const resumed = iperfResult('iperf3: error - unable to connect\r\nConnecting to host 192.0.2.10, port 5201\r\n' + finished);
assert.equal(resumed.state, 'completed');
assert.equal(resumed.rate, '941 Mbits/sec');
assert.equal(resumed.lines.some(line => line.includes('error')), false);
const partial = iperfResult(finished + 'Connecting to host 192.0.2.20, port 5201\r\n[ 5] 0.00-1.00 sec 100 MBytes 800 Mbits/sec\r\n');
assert.equal(partial.state, 'insufficient');
assert.equal(partial.rate, '');
assert.equal(partial.lines.some(line => line.includes('941')), false);
assert.equal(iperfResult('[ 5] 0-10 sec 400 Mbits/sec receiver\r\n[ 7] 0-10 sec 450 Mbits/sec receiver\r\niperf Done.').rate, '');
assert.equal(iperfResult('rate = 999 Mbits/sec receiver\r\n').state, 'insufficient');
assert.equal(iperfResult('[ 5] 0.00-0.00 sec 999 Mbits/sec receiver\r\n').rate, '');
assert.equal(iperfResult('C:\\test>iperf3 -c 192.0.2.10\r\n[ 5] 0.0-10.0 sec 900 Mbits/sec sender\r\nC:\\test>\r\n').rate, '');
assert.equal(iperfResult('Client connecting to 192.0.2.10, TCP port 5001\r\n[ 3] 0.0-10.0 sec 950 Mbits/sec\r\nC:\\test>\r\n').rate, '950 Mbits/sec');
assert.equal(iperfResult('iperf Done.\r\n').rate, '');
assert.equal(iperfResult(finished + 'Accepted connection from 192.0.2.10, port 12345\r\n').state, 'insufficient');
assert.ok(iperfResult('x\n'.repeat(100)).lines.length <= 8);
console.log('Flow output: ANSI/UTF-8 chunk boundaries, echo rejection, iperf summaries, partial runs and errors passed.');
