'use strict';
const assert = require('node:assert/strict');
require('../ui/test-cases.js');
const parse = globalThis.TerminalGridTestCases.parse;
const cases = parse('\uFEFFcode,title,roles,expected,flow,usbCount,serials\r\nDEMO-1,"A, B","DUT 1\nDUT 2","rate ""ok""",Fixture,2,"USB1,USB2"\r\nDEMO-2,Y,,,,0,', [], [{ id: 'f', name: 'Fixture' }]);
assert.equal(cases[0].title, 'A, B');
assert.equal(cases[0].notes, '裝置角色\nDUT 1\nDUT 2\n\n驗收條件\nrate "ok"');
assert.equal(cases[0].flowId, 'f');
assert.equal(cases[0].serials, 'USB1, USB2');
assert.equal(cases[1].usbCount, 0);
assert.equal(parse('code\ttitle\tfeasibility\nDEMO-3\tNAN\texternal', [], [])[0].feasibility, 'external');
assert.throws(() => parse('code,title\nDEMO-1,Q\ndemo-1,W', [], []), /重複/);
assert.throws(() => parse('code,title\nDEMO-1,Q', cases, []), /重複/);
assert.throws(() => parse('code,title,flow\nDEMO-1,Q,Unknown', [], []), /唯一/);
assert.throws(() => parse('code,title,usbCount\nDEMO-1,Q,17', [], []), /0–16/);
assert.throws(() => parse('code,title\nDEMO-1,"Q', [], []), /引號/);
const { defaults, makeDefault, createApFlow, usbDevices, chooseDevices } = globalThis.TerminalGridTestCases;
const usb = value => ({ kind: 'device', usb: true, value });
const available = usbDevices([usb('USB3'), usb('USB2'), usb('USB1'), usb('USB2'), { kind: 'device', usb: false, value: 'LAN1' }]);
assert.equal(available.length, 3);
assert.deepEqual(chooseDevices(available, ['USB1', 'USB2'], 2), ['USB1', 'USB2']);
assert.deepEqual(chooseDevices(available.slice(0, 2), ['USB1', 'USB2'], 2), []);
assert.deepEqual(chooseDevices(available, [], 2), []);
assert.deepEqual(chooseDevices(available.slice(0, 2), [], 2), ['USB3', 'USB2']);
assert.equal(new Set(defaults.map(p => p.code)).size, 8);
const original = [{ code: 'nan-ping' }, { code: 'NAN-PING-2' }];
const copy = makeDefault(defaults[0], original, 'flow-1', ['USB1', 'USB2'], '');
assert.equal(copy.code, 'NAN-PING-3');
assert.equal(copy.usbCount, 2);
assert.equal(copy.flowId, 'flow-1');
assert.equal(original.length, 2);
const apValues = { folder: '', appDir: 'C:\\App Folder\\', python: 'C:\\Tools\\python.exe',
  serial: 'USB1', ssid: '測試 AP', bssid: '00:11:22:33:44:55', timeout: '30' };
const ap = createApFlow(defaults.find(p => p.state === 'connected'), apValues);
assert.match(ap.workspace.slots[0].tabs[0].args, /^"C:\\App Folder\\tools\\wait_wifi_ap\.py".*"--ssid=測試 AP" "--bssid=00:11:22:33:44:55"$/);
assert.deepEqual(ap.steps.map(s => s.action), ['pause', 'stop', 'start', 'exit']);
assert.equal(ap.steps.at(-1).timeoutMs, 45000);
const disconnected = createApFlow(defaults.find(p => p.state === 'disconnected'), apValues);
assert.ok(!disconnected.workspace.slots[0].tabs[0].args.includes('--ssid'));
assert.throws(() => createApFlow(defaults.find(p => p.state === 'connected'), { ...apValues, ssid: '測'.repeat(11) }), /32 bytes/);
console.log('TC import: CSV, TSV, multiline notes, flow binding, conflicts and validation passed.');
